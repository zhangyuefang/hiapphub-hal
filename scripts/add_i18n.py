def translate_desc(en: str) -> str:
    """Translate English description to Chinese using dictionary."""
    if en in EN_ZH:
        return EN_ZH[en]
    
    if en in PHRASE_MAP:
        return PHRASE_MAP[en]
    
    zh = en
    for phrase, trans in sorted(PHRASE_MAP.items(), key=lambda x: -len(x[0])):
        zh = zh.replace(phrase, trans)
    
    for en_word, zh_word in sorted(TERM_MAP.items(), key=lambda x: -len(x[0])):
        zh = re.sub(r'\b' + re.escape(en_word) + r'\b', zh_word, zh)
    
    for en_word, zh_word in sorted(NOUN_MAP.items(), key=lambda x: -len(x[0])):
        zh = re.sub(r'\b' + re.escape(en_word) + r's?\b', zh_word, zh, flags=re.IGNORECASE)
    
    zh = re.sub(r'([\u4e00-\u9fff])\s+([\u4e00-\u9fff])', r'\1\2', zh)
    zh = re.sub(r'([\u4e00-\u9fff])\s+([\u4e00-\u9fff])', r'\1\2', zh)
    
    return zh


def translate_param_desc(en: str) -> str:
    """Translate parameter/return description to Chinese."""
    if not en or en == "-":
        return en
    
    if en in PHRASE_MAP:
        return PHRASE_MAP[en]
    
    for en_word, zh_word in sorted(NOUN_MAP.items(), key=lambda x: -len(x[0])):
        en_lower = en.lower()
        if en_lower == en_word.lower():
            return zh_word
    
    return translate_desc(en)


def process_module(mod_name: str, lib_path: str):
    """Process a single module's lib.rs to add i18n fields."""
    with open(lib_path, 'r') as f:
        content = f.read()
    
    json_match = re.search(r'r#"(\{[\s\S]*?\})"#', content)
    if not json_match:
        json_match = re.search(r'r##"(\{[\s\S]*?\})"##', content)
    if not json_match:
        print(f"  WARNING: Could not find JSON in {mod_name}")
        return False
    
    json_str = json_match.group(1)
    
    try:
        desc = json.loads(json_str)
    except json.JSONDecodeError as e:
        print(f"  WARNING: JSON parse error in {mod_name}: {e}")
        return False
    
    short_name = mod_name.replace('hap-mod-', '')
    
    if short_name in MODULE_OVERVIEWS:
        ov = MODULE_OVERVIEWS[short_name]
        desc['overview'] = ov['en-US']
        desc['overviews'] = ov
    
    if desc.get('descriptions') and 'zh-CN' in desc['descriptions']:
        pass
    elif desc.get('description'):
        zh_desc = translate_desc(desc['description'])
        desc['descriptions'] = {"zh-CN": zh_desc, "en-US": desc['description']}
    
    for fn in desc.get('functions', []):
        fn_en = fn.get('description', '') or ''
        if fn_en:
            fn_zh = translate_desc(fn_en)
            fn['descriptions'] = {"zh-CN": fn_zh, "en-US": fn_en}
        
        for param in fn.get('params', []):
            p_en = param.get('desc', '') or ''
            if p_en:
                p_zh = translate_param_desc(p_en)
                param['descs'] = {"zh-CN": p_zh, "en-US": p_en}
        
        ret = fn.get('returns', {})
        r_en = ret.get('desc', '') or ''
        if r_en:
            r_zh = translate_param_desc(r_en)
            ret['descs'] = {"zh-CN": r_zh, "en-US": r_en}
    
    new_json = json.dumps(desc, ensure_ascii=False, indent=2)
    
    old_block = json_match.group(0)
    if old_block.startswith('r##"'):
        new_block = f'r##"{new_json}"##'
    else:
        if '"#' in new_json:
            new_block = f'r##"{new_json}"##'
        else:
            new_block = f'r#"{new_json}"#'
    
    new_content = content[:json_match.start()] + new_block + content[json_match.end():]
    
    with open(lib_path, 'w') as f:
        f.write(new_content)
    
    fn_count = len(desc.get('functions', []))
    print(f"  OK: {fn_count} functions processed")
    return True


def main():
    total = 0
    success = 0
    for mod_dir in sorted(os.listdir(MODULES_DIR)):
        if not mod_dir.startswith('hap-mod-'):
            continue
        lib_path = os.path.join(MODULES_DIR, mod_dir, 'src', 'lib.rs')
        if not os.path.exists(lib_path):
            continue
        total += 1
        print(f"Processing {mod_dir}...")
        if process_module(mod_dir, lib_path):
            success += 1
    
    print(f"\nDone: {success}/{total} modules processed")


if __name__ == '__main__':
    main()
